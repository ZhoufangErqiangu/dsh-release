#!/usr/bin/env bash
# Provide a relocatable musl cross toolchain for the Landlock launcher.
#
# The DSH native package declares a *static musl* `bin/landlock-run` plus two
# Node-API addons (glibc and musl). Building the full native set therefore
# needs musl-gcc, which Ubuntu does not install by default. Instead of
# requiring root, this script downloads the two small pinned Ubuntu packages,
# verifies their digests, extracts them under .work/, and generates a
# musl-gcc wrapper whose specs point at the extracted prefix.
#
# The result is a build-time tool only: no musl software is shipped in the deb.

set -euo pipefail
# shellcheck source=common.sh
. "$(dirname "${BASH_SOURCE[0]}")/common.sh"

[ "$(host_deb_arch)" = "amd64" ] || die "the pinned musl toolchain is amd64-only"

MUSL_DIR="$WORK/musl"
MUSL_DEBS="$WORK/musl-debs"
MUSL_VERSION="1.2.4-2"
# Mirrors are tried in order; MUSL_BASE_URL lets a restricted network point at
# an internal Ubuntu archive mirror first.
MUSL_MIRRORS=()
if [ -n "${MUSL_BASE_URL:-}" ]; then MUSL_MIRRORS+=("$MUSL_BASE_URL"); fi
MUSL_MIRRORS+=(
  "https://archive.ubuntu.com/ubuntu/pool/universe/m/musl"
  "https://mirrors.tuna.tsinghua.edu.cn/ubuntu/pool/universe/m/musl"
)
MUSL_TOOLS_DEB="musl-tools_${MUSL_VERSION}_amd64.deb"
MUSL_DEV_DEB="musl-dev_${MUSL_VERSION}_amd64.deb"
MUSL_TOOLS_SHA256="46c01d212d3eb3a1322693089037f0a5c92383a089d39c392db3c86c19ffb229"
MUSL_DEV_SHA256="4b451ecb6a0f8469883058cf22a807f3bd9cc16d115cc08b7efc35fe8eb44db2"

wrapper="$MUSL_DIR/bin/musl-gcc"
if [ -f "$MUSL_DIR/.ready" ] && [ -x "$wrapper" ]; then
  step "musl toolchain already prepared"
  exit 0
fi

require_cmd curl "curl is required to download the pinned musl toolchain"
require_cmd dpkg-deb "dpkg-deb is required to extract the musl toolchain"

mkdir -p "$MUSL_DEBS" "$MUSL_DIR"
fetch_deb() {
  local name="$1" checksum="$2" path="$MUSL_DEBS/$1"
  if [ ! -f "$path" ]; then
    local base ok=0
    for base in "${MUSL_MIRRORS[@]}"; do
      log "downloading $name from $base"
      if curl -fsSL --retry 3 --retry-delay 2 -o "$path.part" "$base/$name"; then
        mv "$path.part" "$path"
        ok=1
        break
      fi
      rm -f "$path.part"
      warn "download failed from $base"
    done
    [ "$ok" = 1 ] || die "could not download $name from any configured mirror (set MUSL_BASE_URL)"
  fi
  printf '%s  %s\n' "$checksum" "$path" | sha256sum -c --quiet - \
    || die "checksum mismatch for $name; remove $path and retry"
}

fetch_deb "$MUSL_TOOLS_DEB" "$MUSL_TOOLS_SHA256"
fetch_deb "$MUSL_DEV_DEB" "$MUSL_DEV_SHA256"

log "extracting musl toolchain into $MUSL_DIR"
rm -rf "$MUSL_DIR"
mkdir -p "$MUSL_DIR"
dpkg-deb -x "$MUSL_DEBS/$MUSL_TOOLS_DEB" "$MUSL_DIR"
dpkg-deb -x "$MUSL_DEBS/$MUSL_DEV_DEB" "$MUSL_DIR"

# The distro wrapper hardcodes /usr/lib/x86_64-linux-musl and
# /usr/include/x86_64-linux-musl. Rewrite the specs file to the extracted
# prefix and provide a wrapper that points at it.
specs="$MUSL_DIR/usr/lib/x86_64-linux-musl/musl-gcc.specs"
[ -f "$specs" ] || die "musl-gcc.specs missing from the extracted toolchain"
sed -e "s|/usr/lib/x86_64-linux-musl|$MUSL_DIR/usr/lib/x86_64-linux-musl|g" \
    -e "s|/usr/include/x86_64-linux-musl|$MUSL_DIR/usr/include/x86_64-linux-musl|g" \
    "$specs" > "$specs.patched"

mkdir -p "$MUSL_DIR/bin"
cat > "$wrapper" <<EOF
#!/bin/sh
# Generated by scripts/prepare-musl.sh — relocatable musl-gcc.
exec gcc "\$@" -specs "$specs.patched"
EOF
chmod +x "$wrapper"

# Sanity check: a static executable that runs here.
probe_dir="$WORK/musl-probe"
rm -rf "$probe_dir"
mkdir -p "$probe_dir"
printf 'int main(void) { return 0; }\n' > "$probe_dir/probe.c"
"$wrapper" -static -s -o "$probe_dir/probe" "$probe_dir/probe.c" \
  || die "musl-gcc could not build a static probe"
"$probe_dir/probe" || die "musl static probe does not run"
if command -v readelf >/dev/null 2>&1; then
  LC_ALL=C readelf -h "$probe_dir/probe" | grep -Eq 'Type:[[:space:]]+EXEC' \
    || die "musl probe is not a static executable"
fi
rm -rf "$probe_dir"
touch "$MUSL_DIR/.ready"
log "${C_GREEN}musl toolchain ready${C_RESET}: $wrapper"
